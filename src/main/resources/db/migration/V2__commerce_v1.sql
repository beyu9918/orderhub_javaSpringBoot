-- Keep all original demo data and endpoints. V1 uses the 18 plural-named core tables.
ALTER TABLE inventory RENAME TO legacy_inventory;

CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE, username VARCHAR(50) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, phone VARCHAR(30),
 role VARCHAR(10) NOT NULL CHECK (role IN ('USER','ADMIN')),
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DISABLED')),
 token_version INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE addresses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 receiver_name VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
 province VARCHAR(100) NOT NULL, city VARCHAR(100) NOT NULL, district VARCHAR(100) NOT NULL,
 detail_address VARCHAR(500) NOT NULL, postal_code VARCHAR(20),
 is_default BOOLEAN NOT NULL DEFAULT FALSE, default_slot INTEGER,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id, default_slot),
 CHECK ((is_default AND default_slot IS NOT NULL AND default_slot = 1) OR (NOT is_default AND default_slot IS NULL))
);
CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL,
 parent_id BIGINT REFERENCES categories(id), sort_order INTEGER NOT NULL DEFAULT 0,
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category_id BIGINT NOT NULL REFERENCES categories(id),
 name VARCHAR(200) NOT NULL, description VARCHAR(2000) NOT NULL DEFAULT '', brand VARCHAR(100), image_url VARCHAR(500),
 status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','ACTIVE','INACTIVE')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE product_skus (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id),
 sku_code VARCHAR(64) NOT NULL UNIQUE, attributes JSONB NOT NULL,
 price NUMERIC(12,2) NOT NULL CHECK (price > 0),
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE inventory (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku_id BIGINT NOT NULL UNIQUE REFERENCES product_skus(id),
 available_stock INTEGER NOT NULL DEFAULT 0 CHECK (available_stock BETWEEN 0 AND 1000000000),
 reserved_stock INTEGER NOT NULL DEFAULT 0 CHECK (reserved_stock BETWEEN 0 AND 1000000000),
 version INTEGER NOT NULL DEFAULT 0,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE carts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE cart_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cart_id BIGINT NOT NULL REFERENCES carts(id),
 sku_id BIGINT NOT NULL REFERENCES product_skus(id), quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 999),
 selected BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(cart_id,sku_id)
);
CREATE TABLE coupons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
 discount_type VARCHAR(16) NOT NULL CHECK (discount_type IN ('FIXED','PERCENTAGE')),
 discount_value NUMERIC(12,2) NOT NULL CHECK (discount_value > 0),
 minimum_amount NUMERIC(12,2) NOT NULL CHECK (minimum_amount >= 0),
 total_quantity INTEGER NOT NULL CHECK (total_quantity >= 0),
 claimed_quantity INTEGER NOT NULL DEFAULT 0 CHECK (claimed_quantity >= 0 AND claimed_quantity <= total_quantity),
 start_at TIMESTAMP WITH TIME ZONE NOT NULL, expire_at TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (expire_at > start_at), CHECK (discount_type <> 'PERCENTAGE' OR discount_value <= 100)
);
CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_no VARCHAR(40) NOT NULL UNIQUE,
 user_id BIGINT NOT NULL REFERENCES users(id), address_id BIGINT REFERENCES addresses(id) ON DELETE SET NULL, address_snapshot JSONB NOT NULL,
 request_key VARCHAR(64) NOT NULL, request_hash VARCHAR(64) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING_PAYMENT','PAID','PROCESSING','SHIPPED','DELIVERED','COMPLETED','CANCELLED','REFUND_REQUESTED','REFUNDED')),
 subtotal_amount NUMERIC(12,2) NOT NULL CHECK (subtotal_amount >= 0),
 discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0 AND discount_amount <= subtotal_amount),
 shipping_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (shipping_amount >= 0),
 payable_amount NUMERIC(12,2) NOT NULL CHECK (payable_amount = subtotal_amount - discount_amount + shipping_amount),
 coupon_id BIGINT REFERENCES coupons(id), remark VARCHAR(500), cancel_reason VARCHAR(500),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 paid_at TIMESTAMP WITH TIME ZONE, shipped_at TIMESTAMP WITH TIME ZONE, delivered_at TIMESTAMP WITH TIME ZONE,
 completed_at TIMESTAMP WITH TIME ZONE, cancelled_at TIMESTAMP WITH TIME ZONE,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,request_key)
);
CREATE TABLE order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 product_id BIGINT NOT NULL REFERENCES products(id), sku_id BIGINT NOT NULL REFERENCES product_skus(id),
 product_name VARCHAR(200) NOT NULL, sku_attributes JSONB NOT NULL, product_image VARCHAR(500),
 unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0), quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 999),
 subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal = unit_price * quantity),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(order_id,sku_id)
);
CREATE TABLE inventory_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku_id BIGINT NOT NULL REFERENCES product_skus(id),
 order_id BIGINT REFERENCES orders(id), change_type VARCHAR(24) NOT NULL
 CHECK (change_type IN ('PURCHASE','ORDER_RESERVED','ORDER_CANCELLED','ORDER_COMPLETED','ADMIN_ADJUSTMENT','REFUND_RETURN')),
 quantity INTEGER NOT NULL, before_stock INTEGER NOT NULL, after_stock INTEGER NOT NULL,
 before_reserved INTEGER NOT NULL, after_reserved INTEGER NOT NULL,
 operator_id BIGINT REFERENCES users(id), remark VARCHAR(500),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE order_status_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 from_status VARCHAR(20), to_status VARCHAR(20) NOT NULL,
 operator_type VARCHAR(10) NOT NULL CHECK (operator_type IN ('USER','ADMIN','SYSTEM')),
 operator_id BIGINT REFERENCES users(id), reason VARCHAR(500),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payment_no VARCHAR(40) NOT NULL UNIQUE,
 order_id BIGINT NOT NULL REFERENCES orders(id), method VARCHAR(10) NOT NULL DEFAULT 'MOCK' CHECK (method = 'MOCK'),
 amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
 status VARCHAR(10) NOT NULL CHECK (status IN ('PENDING','SUCCESS','FAILED','REFUNDED')),
 transaction_id VARCHAR(64) UNIQUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 paid_at TIMESTAMP WITH TIME ZONE, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE shipments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
 carrier VARCHAR(100) NOT NULL, tracking_number VARCHAR(100) NOT NULL UNIQUE,
 status VARCHAR(12) NOT NULL CHECK (status IN ('READY','SHIPPED','IN_TRANSIT','DELIVERED')),
 shipped_at TIMESTAMP WITH TIME ZONE, delivered_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE refunds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, refund_no VARCHAR(40) NOT NULL UNIQUE,
 order_id BIGINT NOT NULL REFERENCES orders(id), user_id BIGINT NOT NULL REFERENCES users(id),
 payment_id BIGINT NOT NULL REFERENCES payments(id), amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
 reason VARCHAR(500) NOT NULL, status VARCHAR(12) NOT NULL
 CHECK (status IN ('REQUESTED','APPROVED','REJECTED','COMPLETED','CANCELLED')),
 previous_order_status VARCHAR(20) NOT NULL CHECK (previous_order_status IN ('PAID','PROCESSING')),
 admin_remark VARCHAR(500), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 approved_at TIMESTAMP WITH TIME ZONE, completed_at TIMESTAMP WITH TIME ZONE,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE user_coupons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 coupon_id BIGINT NOT NULL REFERENCES coupons(id),
 status VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','USED','EXPIRED')),
 order_id BIGINT UNIQUE REFERENCES orders(id), claimed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 used_at TIMESTAMP WITH TIME ZONE, expire_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(user_id,coupon_id), CHECK ((status = 'USED' AND order_id IS NOT NULL) OR (status <> 'USED' AND order_id IS NULL))
);
CREATE TABLE audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(64) NOT NULL, resource_type VARCHAR(40) NOT NULL, resource_id BIGINT,
 before_value JSONB, after_value JSONB, ip_address VARCHAR(64),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX v1_category_parent ON categories(parent_id,sort_order,id);
CREATE INDEX v1_address_user ON addresses(user_id,id);
CREATE INDEX v1_product_category_status ON products(category_id,status,id);
CREATE INDEX v1_product_status ON products(status,id);
CREATE INDEX v1_sku_product_status ON product_skus(product_id,status,id);
CREATE INDEX v1_sku_price ON product_skus(status,price,id);
CREATE INDEX v1_order_user_created ON orders(user_id,created_at DESC,id DESC);
CREATE INDEX v1_order_user_status ON orders(user_id,status,created_at DESC,id DESC);
CREATE INDEX v1_order_status_created ON orders(status,created_at,id);
CREATE INDEX v1_order_status_delivered ON orders(status,delivered_at,id);
CREATE INDEX v1_item_order ON order_items(order_id,id);
CREATE INDEX v1_payment_order ON payments(order_id,id);
CREATE INDEX v1_refund_order_status ON refunds(order_id,status,id);
CREATE INDEX v1_inventory_sku_created ON inventory_logs(sku_id,created_at DESC,id DESC);
CREATE INDEX v1_status_order_created ON order_status_logs(order_id,created_at,id);
CREATE INDEX v1_user_coupon_status ON user_coupons(user_id,status,expire_at);
CREATE INDEX v1_coupon_expiry ON user_coupons(status,expire_at,id);
CREATE INDEX v1_audit_admin_created ON audit_logs(admin_id,created_at DESC,id DESC);
