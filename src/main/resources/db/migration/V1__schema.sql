CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    category VARCHAR(100) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE inventory (
    product_id BIGINT PRIMARY KEY REFERENCES product(id),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE cart_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 999),
    UNIQUE(user_id, product_id)
);
CREATE TABLE shop_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(36) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    request_key VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('CREATED', 'CANCELLED')),
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, request_key)
);
CREATE TABLE order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES shop_order(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    product_name VARCHAR(200) NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal = unit_price * quantity),
    UNIQUE(order_id, product_id)
);
CREATE INDEX idx_product_active_category_id ON product(active, category, id);
CREATE INDEX idx_product_active_id ON product(active, id);
CREATE INDEX idx_order_user_created_id ON shop_order(user_id, created_at DESC, id DESC);
CREATE INDEX idx_order_user_status_created_id ON shop_order(user_id, status, created_at DESC, id DESC);
CREATE INDEX idx_cart_product ON cart_item(product_id);
CREATE INDEX idx_order_item_product ON order_item(product_id);
